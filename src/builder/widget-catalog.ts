/** Fallback category for widget types not in the catalog (e.g. new or site-specific widgets). */
export const WIDGET_CATALOG_FALLBACK: WidgetCatalogEntry = { category: "content", icon: "puzzle" }

export function widgetCatalogEntry(type: string): WidgetCatalogEntry {
  if (Object.prototype.hasOwnProperty.call(WIDGET_CATALOG, type)) return WIDGET_CATALOG[type]
  if (type.startsWith("resume-")) return { category: "resume", icon: "file-user" }
  if (type.startsWith("poetry-") || type.startsWith("poem-")) return { category: "poetry", icon: WIDGET_CATALOG_FALLBACK.icon }
  if (type.startsWith("academy-")) return { category: "academy", icon: WIDGET_CATALOG_FALLBACK.icon }
  if (type.startsWith("webina-")) return { category: "webina", icon: WIDGET_CATALOG_FALLBACK.icon }
  return WIDGET_CATALOG_FALLBACK
}

/** Group a list of widget defs by catalog category, preserving category order and dropping empty groups. */
export function groupWidgetsByCatalog<T extends { type: string }>(widgets: readonly T[]): { category: WidgetCatalogCategory; widgets: T[] }[] {
  return WIDGET_CATALOG_CATEGORIES.map((category) => ({ category, widgets: widgets.filter((w) => widgetCatalogEntry(w.type).category === category.id) })).filter((g) => g.widgets.length > 0)
}

/** Every lucide icon name used by the catalog (for static import maps). */
export function widgetCatalogIconNames(): string[] {
  return Array.from(new Set([...WIDGET_CATALOG_CATEGORIES.map((c) => c.icon), ...Object.values(WIDGET_CATALOG).map((e) => e.icon), WIDGET_CATALOG_FALLBACK.icon, "file-user"]))
}
